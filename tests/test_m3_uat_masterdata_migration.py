"""Master Data UAT migration checks; no live database writes."""
import pytest
from app.uat_masterdata_migration import SOURCE, generate


def test_masterdata_schema_includes_approval_and_audit_integrity():
    ddl = generate(SOURCE.read_text(encoding="utf-8"))
    assert ddl.count("CREATE TABLE IF NOT EXISTS") == 9
    assert ddl.count("CREATE TRIGGER ") == 2
    assert "md_change_requests" in ddl
    assert "md_audit" in ddl
    assert "MASTER_AUDIT_IMMUTABLE" in ddl
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "DELETE FROM" not in ddl


def test_schema_cannot_be_silently_truncated():
    with pytest.raises(ValueError, match="schema not found"):
        generate("def init_schema(c): pass")
