PINNED_SHA = "79968230bd5601142d9239c739853b64ed9d2f82"
PINNED_DIR = Path(__file__).resolve().parents[1] / "m3-pinned"
ACTOR = {"user_ref": "EPHEMERAL-MAKER", "office_code": "RTM", "username": "md.maker"}
KEY = "ephemeral-pg-atomic-rollback-20261104"

assert subprocess.check_output(
    ["git", "-C", str(PINNED_DIR), "rev-parse", "HEAD"], text=True
).strip() == PINNED_SHA
sys.path.insert(0, str(PINNED_DIR))
from app import masterdata as md  # noqa: E402
