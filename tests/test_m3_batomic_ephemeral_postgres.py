"""Real PostgreSQL transaction regression for the pinned M3 atomic endpoint.

The database is a throwaway GitHub Actions service at localhost and has NO
connection to Neon, Supabase, ANCLINE, or production. Authentication and
business row-validation worker are explicitly mocked: this proves only
PostgreSQL transaction/ledger/lock behavior of the pinned endpoint.
"""
