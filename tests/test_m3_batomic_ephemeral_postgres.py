def isolated_dsn():
    dsn = os.getenv("M3_EPHEMERAL_PG_DSN", "")
    u = urlsplit(dsn)
    if (u.scheme not in ("postgres", "postgresql")
            or u.hostname not in ("127.0.0.1", "localhost")
            or u.port != 5432 or u.path != "/m3_atomic_test"
            or u.username != "m3test"
            or not u.password
            or os.getenv("M3_PRODUCTION_TRAFFIC") != "OFF"
            or os.getenv("M3_LIVE_PROVIDERS") != "OFF"
            or os.getenv("M3_REAL_MONEY") != "OFF"
            or os.getenv("DATABASE_URL", "") != ""):
        raise RuntimeError("EPHEMERAL_POSTGRES_TARGET_GUARD_FAILED")
    return dsn


@pytest.fixture
def harness(monkeypatch):
    dsn = isolated_dsn()
    # Only the ephemeral test PostgreSQL service ever receives DDL and data.
    with psycopg.connect(dsn, autocommit=True) as setup:
        with setup.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS md_bulk_idempotency(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    maker TEXT NOT NULL, scope TEXT NOT NULL, idem_key TEXT NOT NULL,
                    request_hash TEXT NOT NULL, response_json TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    UNIQUE(maker,scope,idem_key)
                )""")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS md_change_requests(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    record_key TEXT NOT NULL, change_ref TEXT NOT NULL
                )""")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS md_audit(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    record_key TEXT NOT NULL, change_ref TEXT NOT NULL
                )""")
            cur.execute("TRUNCATE md_bulk_idempotency,md_change_requests,md_audit RESTART IDENTITY")
    monkeypatch.setattr(md, "connect", lambda: db_module.PostgresConnectionCompat(dsn))
    monkeypatch.setattr(md, "using_postgres", lambda: True)
    monkeypatch.setattr(db_module, "using_postgres", lambda: True)
    monkeypatch.setattr(md, "authenticated_actor", lambda *_: (ACTOR, {"MASTER_DATA"}))
    state = {"calls": 0, "fail_on": None}

    def worker(change, token, c=None, owns_transaction=True):
        assert c is not None and owns_transaction is False
        assert token == "local-ephemeral-session"
        state["calls"] += 1
        if state["calls"] == state["fail_on"]:
            raise HTTPException(422, {"code": "EPHEMERAL_LATE_ROW_REJECTION"})
        ref = "PG-TEST-" + str(state["calls"])
        c.execute("INSERT INTO md_change_requests(record_key,change_ref) VALUES(?,?)",
                  (change.record_key, ref))
        c.execute("INSERT INTO md_audit(record_key,change_ref) VALUES(?,?)",
                  (change.record_key, ref))
        return {"change_ref": ref}

    monkeypatch.setattr(md, "_create_change_worker", worker)
    yield dsn, state


def counts(dsn):
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            result = []
            for table in ("md_change_requests", "md_audit", "md_bulk_idempotency"):
                cur.execute(f"SELECT COUNT(*) FROM {table}")
                result.append(cur.fetchone()[0])
            return tuple(result)


def payload(name="Disposable B"):
    return md.BulkRequest(domain="customer", rows=[
        md.BulkRow(record_key="LOCAL-A", operation="CREATE",
                   payload={"name": "Disposable A"}, reason="Ephemeral PostgreSQL-only test"),
        md.BulkRow(record_key="LOCAL-B", operation="CREATE",
                   payload={"name": name}, reason="Ephemeral PostgreSQL-only test"),
    ])


def submit(data, key=KEY):
    return md.bulk_submit_atomic(
        data, idempotency_key=key, x_m3_session="local-ephemeral-session")


def test_postgres_late_row_rollback_and_safe_retry(harness):
    dsn, state = harness
    state["fail_on"] = 2
    with pytest.raises(HTTPException) as error:
        submit(payload())
    assert error.value.status_code == 422
    assert counts(dsn) == (0, 0, 0)
    state["fail_on"] = None
    result = submit(payload())
    assert result["atomic"] is True and result["pending"] == 2
    assert counts(dsn) == (2, 2, 1)


def test_postgres_idempotent_replay_without_extra_writes(harness):
    dsn, state = harness
    first = submit(payload())
    assert submit(payload()) == first
    assert state["calls"] == 2
    assert counts(dsn) == (2, 2, 1)


def test_postgres_payload_conflict_409_without_extra_writes(harness):
    dsn, state = harness
    submit(payload())
    with pytest.raises(HTTPException) as error:
        submit(payload("Different customer name"))
    assert error.value.status_code == 409
    assert error.value.detail["code"] == "BULK_IDEMPOTENCY_PAYLOAD_CONFLICT"
    assert state["calls"] == 2
    assert counts(dsn) == (2, 2, 1)


def test_postgres_permission_denied_without_writes(harness, monkeypatch):
    dsn, state = harness
    monkeypatch.setattr(md, "authenticated_actor",
                        lambda *_: (ACTOR, {"VIEWER"}))
    with pytest.raises(HTTPException) as error:
        submit(payload())
    assert error.value.status_code == 403
    assert counts(dsn) == (0, 0, 0)
    assert state["calls"] == 0


def test_postgres_ledger_key_scope_isolation(harness):
    dsn, state = harness
    first = submit(payload())
    assert first["atomic"] is True
    assert submit(payload(), key=KEY + "-different")["atomic"] is True
    assert counts(dsn) == (4, 4, 2)
    assert state["calls"] == 4


