"""Offline PostgreSQL migration integrity checks; never connect to production."""
import re
import pytest
from app.uat_schema_migration import SCHEMA, ddl_from_sqlite


def test_frozen_schema_migration_preserves_all_immutable_triggers():
    ddl = ddl_from_sqlite(SCHEMA.read_text(encoding="utf-8"))
    source = SCHEMA.read_text(encoding="utf-8")
    original = re.findall(r"CREATE TRIGGER IF NOT EXISTS\s+([A-Za-z_]\w*)", source)
    migrated = re.findall(r"CREATE TRIGGER\s+([A-Za-z_]\w*)", ddl)
    assert len(original) == 18
    assert sorted(original) == sorted(migrated)
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "CREATE TABLE" in ddl
    assert "GL_AUDIT_IMMUTABLE" in ddl
    assert "TREASURY_AUDIT_IMMUTABLE" in ddl
    assert "WHEN OLD.module" not in ddl


def test_unsupported_trigger_cannot_be_silently_dropped():
    bad = "CREATE TABLE scratch(id INTEGER PRIMARY KEY); CREATE TRIGGER IF NOT EXISTS custom AFTER INSERT ON scratch BEGIN SELECT 1; END;"
    with pytest.raises(ValueError, match="Unsupported integrity trigger"):
        ddl_from_sqlite(bad)
