"""Generate reviewable PostgreSQL DDL from the frozen M3 SQLite schema.

Offline only. Does not connect to any database, execute SQL, or deploy.
Unsupported schema constructs cause an error instead of dropping integrity rules.
"""
from pathlib import Path
import re
import sqlite3

SCHEMA = Path(__file__).with_name("schema.sql")


def ddl_from_sqlite(source: str) -> str:
    source = re.sub(r"(?im)^\s*PRAGMA\s+[^;]+;\s*", "", source)
    memory = sqlite3.connect(":memory:")
    try:
        memory.executescript(source)
        items = memory.execute(
            "SELECT type,name,sql FROM sqlite_master "
            "WHERE type IN ('table','index','trigger') AND name NOT LIKE 'sqlite_%' "
            "AND sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid"
        ).fetchall()
    finally:
        memory.close()
    output = ["-- Generated offline from app/schema.sql; UAT only; review before application."]
    trigger_count = 0
    table_count = 0
    for kind, name, statement in items:
        if kind == "table":
            table_count += 1
            ddl = re.sub(r"(?i)\bINTEGER\s+PRIMARY\s+KEY\b",
                         "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement)
            if re.search(r"(?i)\b(AUTOINCREMENT|WITHOUT\s+ROWID|COLLATE\s+NOCASE|GLOB)\b", ddl):
                raise ValueError("Unsupported SQLite table: " + name)
            output.append(ddl.rstrip(";") + ";")
        elif kind == "index":
            if re.search(r"(?i)\b(COLLATE\s+NOCASE|GLOB)\b", statement):
                raise ValueError("Unsupported SQLite index: " + name)
            output.append(statement.rstrip(";") + ";")
        else:
            trigger_count += 1
            match = re.fullmatch(
                r"CREATE TRIGGER IF NOT EXISTS ([a-zA-Z_][\w]*)\s+"
                r"BEFORE (UPDATE|DELETE) ON ([a-zA-Z_][\w]*)\s+"
                r"(?:WHEN OLD\.module LIKE '(gl|treasury):%'\s+)?"
                r"BEGIN SELECT RAISE\(ABORT,'([A-Z_]+)'\); END;?",
                statement.strip(), re.I
            )
            if not match:
                raise ValueError("Unsupported integrity trigger: " + name)
            trigger_name, operation, table, scope, error_code = match.groups()
            fn_name = "m3_uat_block_" + trigger_name
            condition = ("IF OLD.module LIKE '" + scope + ":%' THEN " if scope else "")
            ending = " END IF;" if scope else ""
            output.append(
                "CREATE OR REPLACE FUNCTION " + fn_name + "() RETURNS trigger "
                "LANGUAGE plpgsql AS $$ BEGIN " + condition +
                "RAISE EXCEPTION '" + error_code + "';" + ending +
                " RETURN OLD; END; $$;")
            output.append(
                "CREATE TRIGGER " + trigger_name + " BEFORE " + operation +
                " ON " + table + " FOR EACH ROW EXECUTE FUNCTION " + fn_name + "();"
            )
    if not table_count or not trigger_count:
        raise ValueError("Schema unexpectedly missing tables or integrity triggers")
    return "\n".join(output) + "\n"


def main() -> None:
    print(ddl_from_sqlite(SCHEMA.read_text(encoding="utf-8")))


if __name__ == "__main__":
    main()
