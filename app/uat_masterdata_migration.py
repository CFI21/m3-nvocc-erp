"""Generate isolated PostgreSQL DDL for governed Master Data.

This is an offline migration preview. Never executes SQL or resets data.
"""
from pathlib import Path
import re

SOURCE = Path(__file__).with_name("masterdata.py")


def generate(source: str) -> str:
    match = re.search(r"def init_schema\(c\):\s*c\.executescript\('''([\s\S]*?)'''\)", source)
    if not match:
        raise ValueError("Master Data schema not found")
    raw = match.group(1)
    tables = re.findall(r"CREATE TABLE IF NOT EXISTS[\s\S]*?;", raw, re.I)
    triggers = re.findall(r"CREATE TRIGGER IF NOT EXISTS[\s\S]*?END;", raw, re.I)
    if len(tables) != 9 or len(triggers) != 2:
        raise ValueError("Unexpected Master Data schema shape; review required")
    output = []
    for stmt in tables:
        output.append(re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b",
                             "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                             stmt, flags=re.I))
    for stmt in triggers:
        m = re.fullmatch(
            r"CREATE TRIGGER IF NOT EXISTS\s+(\w+)\s+BEFORE (UPDATE|DELETE) ON (\w+) "
            r"BEGIN SELECT RAISE\(ABORT,'([A-Z_]+)'\); END;", stmt.strip(), re.I)
        if not m:
            raise ValueError("Unsupported Master Data audit trigger")
        name, action, table, error = m.groups()
        fn = "m3_uat_block_" + name
        output.append(f"CREATE OR REPLACE FUNCTION {fn}() RETURNS trigger LANGUAGE plpgsql "
                      f"AS $$ BEGIN RAISE EXCEPTION '{error}'; END; $$;")
        output.append(f"CREATE TRIGGER {name} BEFORE {action} ON {table} "
                      f"FOR EACH ROW EXECUTE FUNCTION {fn}();")
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    print(generate(SOURCE.read_text(encoding="utf-8")))
