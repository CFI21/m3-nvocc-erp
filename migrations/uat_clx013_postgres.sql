-- Dedicated M3 Neon UAT only. Additive CLX-013 readiness schema.
-- Do not apply to production without separate migration approval.
CREATE TABLE IF NOT EXISTS clx013_schema_versions (
  version TEXT PRIMARY KEY, applied_at TEXT NOT NULL, checksum TEXT NOT NULL,
  destructive INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS clx013_request_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts TEXT NOT NULL, request_id TEXT NOT NULL UNIQUE, correlation_id TEXT NOT NULL,
  method TEXT NOT NULL, path TEXT NOT NULL, status_code INTEGER NOT NULL,
  duration_ms DOUBLE PRECISION NOT NULL, actor_role TEXT, office TEXT,
  job_ref TEXT, error_class TEXT
);
CREATE TABLE IF NOT EXISTS clx013_backup_manifests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  backup_ref TEXT NOT NULL UNIQUE, file_name TEXT NOT NULL, sha256 TEXT NOT NULL,
  source_db TEXT NOT NULL, size_bytes INTEGER NOT NULL,
  integrity_status TEXT NOT NULL, created_at TEXT NOT NULL,
  restore_status TEXT, restore_duration_ms DOUBLE PRECISION, restore_evidence_json TEXT
);
CREATE TABLE IF NOT EXISTS clx013_deployment_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_ref TEXT NOT NULL UNIQUE, environment TEXT NOT NULL,
  status TEXT NOT NULL, started_at TEXT NOT NULL, completed_at TEXT,
  gate_json TEXT NOT NULL, smoke_json TEXT, rollback_json TEXT
);
CREATE TABLE IF NOT EXISTS clx013_runtime_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_ref TEXT NOT NULL UNIQUE, ts TEXT NOT NULL, category TEXT NOT NULL,
  severity TEXT NOT NULL, action TEXT NOT NULL, detail_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS clx013_runtime_mode (
  id INTEGER PRIMARY KEY CHECK (id=1), mode TEXT NOT NULL,
  reason TEXT, updated_at TEXT NOT NULL, updated_by TEXT NOT NULL
);
CREATE OR REPLACE FUNCTION clx013_reject_immutable_change()
RETURNS trigger LANGUAGE plpgsql AS $m3$
BEGIN RAISE EXCEPTION 'IMMUTABLE_CLX013_RECORD'; END;
$m3$;
DO $m3$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='clx013_request_log_no_update' AND tgrelid='clx013_request_log'::regclass) THEN
    CREATE TRIGGER clx013_request_log_no_update BEFORE UPDATE ON clx013_request_log FOR EACH ROW EXECUTE FUNCTION clx013_reject_immutable_change();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='clx013_request_log_no_delete' AND tgrelid='clx013_request_log'::regclass) THEN
    CREATE TRIGGER clx013_request_log_no_delete BEFORE DELETE ON clx013_request_log FOR EACH ROW EXECUTE FUNCTION clx013_reject_immutable_change();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='clx013_runtime_events_no_update' AND tgrelid='clx013_runtime_events'::regclass) THEN
    CREATE TRIGGER clx013_runtime_events_no_update BEFORE UPDATE ON clx013_runtime_events FOR EACH ROW EXECUTE FUNCTION clx013_reject_immutable_change();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='clx013_runtime_events_no_delete' AND tgrelid='clx013_runtime_events'::regclass) THEN
    CREATE TRIGGER clx013_runtime_events_no_delete BEFORE DELETE ON clx013_runtime_events FOR EACH ROW EXECUTE FUNCTION clx013_reject_immutable_change();
  END IF;
END $m3$;
