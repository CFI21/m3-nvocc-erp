ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS damage_hold boolean NOT NULL DEFAULT false;
ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS inspection_hold boolean NOT NULL DEFAULT false;
ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS journey_updated_at text;

UPDATE public.containers
SET journey_state=COALESCE(NULLIF(journey_state,''),equipment_status),
    last_event_type=COALESCE(last_event_type,equipment_status),
    journey_updated_at=COALESCE(journey_updated_at,updated_at)
WHERE journey_state IS NULL OR journey_state='';

CREATE TABLE IF NOT EXISTS public.container_journey_exceptions(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exception_ref text NOT NULL UNIQUE,
  container_id bigint NOT NULL REFERENCES public.containers(id) ON DELETE CASCADE,
  job_id bigint REFERENCES public.jobs(id),
  exception_type text NOT NULL,
  severity text NOT NULL,
  status text NOT NULL DEFAULT 'OPEN',
  expected_event text,
  actual_state text,
  due_time text,
  detail text NOT NULL,
  owner_role text,
  owner_ref text,
  resolution_code text,
  resolution_note text,
  created_at text NOT NULL,
  acknowledged_at text,
  resolved_at text,
  created_by text
);
CREATE INDEX IF NOT EXISTS idx_container_journey_exc_queue
ON public.container_journey_exceptions(status,severity,exception_type,created_at);
CREATE INDEX IF NOT EXISTS idx_container_journey_exc_container
ON public.container_journey_exceptions(container_id,status);

CREATE TABLE IF NOT EXISTS public.container_journey_policy(
  policy_key text PRIMARY KEY,
  policy_value text NOT NULL,
  description text NOT NULL,
  updated_at text NOT NULL
);
