UPDATE public.container_events
SET actual_time=COALESCE(actual_time,event_time),event_phase='ACTUAL'
WHERE actual_time IS NULL AND COALESCE(event_phase,'ACTUAL')='ACTUAL';

ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS journey_state text;
ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS last_event_type text;
ALTER TABLE public.containers ADD COLUMN IF NOT EXISTS last_event_time text;
